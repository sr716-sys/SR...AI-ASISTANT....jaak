# Regex to remove control tags like <ctrl10> from text
_CTRL_RE = re.compile(r"<ctrl\d+>", re.IGNORECASE)

# Minimum length for a text chunk to qualify for repetition checking
_REPEAT_MIN = 12


def _is_repeat_chunk(txt: str, buf: list) -> bool:
    """True if this transcript chunk has already been seen this turn.

    Guards against the API re-sending the tail of a response."""
    if len(txt) < _REPEAT_MIN:
        # Exact match for short chunks
        return bool(buf) and txt == buf[-1]
    # Substring match within the buffered history for long chunks
    joined = " ".join(buf)
    return txt in joined

def _clean_transcript(text: str) -> str: 
    """Remove control codes and ASCII control chars from transcript."""   
    text = _CTRL_RE.sub("", text)
    text = re.sub(r"[\x00-\x08\x0b-\x1f]", "", text)
    return text.strip()

